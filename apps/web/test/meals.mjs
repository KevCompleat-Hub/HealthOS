// W16: Mahlzeiten mit BLS ohne Oberfläche geprüft, mit den echten aufbereiteten BLS-Daten.
import { buildSync } from 'esbuild';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const here = path.dirname(fileURLToPath(import.meta.url)); const web = path.resolve(here, '..');
mkdirSync(path.join(web, '.test'), { recursive: true });
writeFileSync(path.join(web, '.test/meals-entry.jsx'), "export * from '../src/beta/bls.js';\nexport * from '../src/beta/meals.jsx';\nexport { emptyState } from '../src/legacy/support.js';\nexport * as D from '@healthos/domain';\n");
const out = path.join(web, '.test/meals.cjs');
buildSync({ entryPoints: [path.join(web, '.test/meals-entry.jsx')], bundle: true, platform: 'node', format: 'cjs', outfile: out, jsx: 'automatic', loader: { '.js': 'jsx' }, external: ['react', 'react-dom'], define: { 'process.env.NEXT_PUBLIC_HEALTHOS_MODE': '"beta"' }, logLevel: 'error' });
const M = createRequire(import.meta.url)(out); const { D } = M;
let n = 0, f = 0; const ok = (c, m) => { n++; if (!c) f++; console.log(`${c ? 'ok  ' : 'FEHL'} ${m}`); };
const fakeFetch = async u => ({ json: async () => JSON.parse(readFileSync(path.join(web, 'public', u), 'utf8')) });
const foods = await M.loadBls(fakeFetch);
ok(foods.length === 7140, `BLS geladen: ${foods.length} Lebensmittel`);
const hf = M.searchBls(foods, 'haferflocken');
ok(hf.length && hf[0].code === 'C133000', `Suche „haferflocken“ in einem Wort trifft die Grundzutat zuerst (${hf.slice(0, 3).map(x => x.name).join(' | ')})`);
const hf2 = M.searchBls(foods, 'Hafer Flocken');
ok(hf2[0] && hf2[0].code === 'C133000', `Suche „Hafer Flocken“ trifft BLS C133000 zuerst (${hf2[0] && hf2[0].name})`);
ok(/^Linse (rot )?reif/.test(M.searchBls(foods, 'linsen')[0].name) && /^Banane roh/.test(M.searchBls(foods, 'banane')[0].name) && /^Apfel roh/.test(M.searchBls(foods, 'apfel')[0].name), 'Grundzutaten vor Gerichten: Linsen, Banane, Apfel');
ok(M.searchBls(foods, 'linsen eintopf')[0].name.startsWith('Linsen-Eintopf'), 'Wer nach einem Gericht sucht, bekommt das Gericht');
ok(M.searchBls(foods, 'linsen').length > 3 && M.searchBls(foods, 'kaese').some(x => /Käse/.test(x.name)), 'Umlaute: „kaese“ findet Käse');
const oat = foods.find(x => x.code === 'C133000');
const p60 = M.portion(oat, 60);
ok(p60.snap.p === 7.9 && p60.snap.fib === 6.6 && p60.snap.kcal === 209 && !p60.gaps.length, `60 g Haferflocken: ${p60.snap.p} g Eiweiß, ${p60.snap.fib} g Ballaststoffe, ${p60.snap.kcal} kcal`);
const withGap = foods.find(x => Object.values(x.v).includes(null));
const pg = M.portion(withGap, 100);
ok(pg.gaps.length > 0 && pg.gaps.every(k => pg.snap[k] === undefined), `Fehlender BLS-Wert wird nicht als 0 gezählt (${withGap.name}: ${pg.gaps.join(', ')})`);
const withTr = foods.find(x => Object.values(x.v).includes('tr'));
ok(M.portion(withTr, 100).trace.length > 0, `Spuren werden markiert (${withTr.name})`);
const cfg = D.normalizeConfig({ goals: ['fitter'], onboardingDone: true });
const today = '2026-10-21';
const st = M.emptyState(today, cfg);
const e1 = M.mealEntry(oat, 60, today, 'Frühstück'), e2 = M.mealEntry(withGap, 100, today, 'Snack');
const ds = M.daySum([e1, e2], today);
ok(ds.count === 2 && ds.incomplete.length > 0 && ds.sum.p >= 7.9, `Tagessumme mit Kennzeichnung unvollständiger Nährstoffe (${ds.incomplete.join(', ')})`);
ok(e1.snap.kcal === 209 && e1.meal === 'Frühstück' && e1.source === 'bls' && e1.bls === 'C133000', 'Eintrag kompatibel mit dem Mahlzeiten-Modell der Referenz');
ok(D.dayNutrition({ meals: [e1] }, today).p === 7.9, 'Kern-Funktion dayNutrition rechnet mit den neuen Einträgen');
ok(M.proteinGoal(st, today).min === null, 'Ohne Gewicht kein Eiweißziel');
const stW = { ...st, weights: [{ id: 'w', date: today, time: '07:00', kg: 80, note: '', source: 'manuell' }] };
const g1 = M.proteinGoal(stW, today);
ok(g1.min === 64 && g1.max === null && /0,8 g/.test(g1.basis), `80 kg ohne viel Sport: ${g1.min} g (DGE 0,8 g/kg)`);
const ws = D.weekStart(today);
const sport = { ...stW, items: [0, 1, 2, 3, 4].map(i => ({ id: `t${i}`, title: 'Training', type: 'training', date: D.addDays(ws, i), time: '18:00', duration: 60, status: 'geplant', taskClass: 'weekly_flexible', priority: 'mittel' })) };
const g2 = M.proteinGoal(sport, today);
ok(g2.min === 96 && g2.max === 160 && /Sport/.test(g2.basis), `80 kg mit 5 Stunden Training: ${g2.min} bis ${g2.max} g (DGE Sport)`);
const fr = M.frequentFoods([e1, { ...e1, id: 'x', date: '2026-10-20', qty: 50 }, e2]);
ok(fr[0].code === 'C133000' && fr[0].count === 2, 'Häufig gegessen: Haferflocken vorn');
ok(M.defaultSlot(480) === 'Frühstück' && M.defaultSlot(780) === 'Mittagessen' && M.defaultSlot(1140) === 'Abendessen', 'Mahlzeit nach Uhrzeit vorausgewählt');
console.log(`\n${n - f} von ${n} Tests Mahlzeiten und BLS bestanden`);
process.exit(f ? 1 : 0);
