// Morning Briefing (W10): Regeln ohne Oberfläche geprüft.
import { buildSync } from 'esbuild';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeFileSync, mkdirSync } from 'node:fs';
const here = path.dirname(fileURLToPath(import.meta.url)); const web = path.resolve(here, '..');
mkdirSync(path.join(web, '.test'), { recursive: true });
writeFileSync(path.join(web, '.test/brief-entry.jsx'), "export { briefingLines } from '../src/beta/briefing.jsx';\nexport { emptyState } from '../src/legacy/support.js';\nexport * as D from '@healthos/domain';\n");
const out = path.join(web, '.test/briefing.cjs');
buildSync({ entryPoints: [path.join(web, '.test/brief-entry.jsx')], bundle: true, platform: 'node', format: 'cjs', outfile: out, jsx: 'automatic', loader: { '.js': 'jsx' }, external: ['react', 'react-dom'], define: { 'process.env.NEXT_PUBLIC_HEALTHOS_MODE': '"beta"' }, logLevel: 'error' });
const { briefingLines, emptyState, D } = createRequire(import.meta.url)(out);
let n = 0, f = 0; const ok = (c, m) => { n++; if (!c) f++; console.log(`${c ? 'ok  ' : 'FEHL'} ${m}`); };
const today = '2026-10-21'; const cfg = D.normalizeConfig({ goals: ['abnehmen', 'fitter'], onboardingDone: true });
const empty = emptyState(today, cfg);
const l0 = briefingLines(empty, cfg, today, 420);
ok(l0.length === 1 && l0[0].kind === 'heute', `Ohne Verlauf nur die Tageszeile, keine erfundene Erfolgsaussage (${l0.map(x => x.text).join(' | ')})`);
ok(/Heute: .+ um \d{2}:\d{2} Uhr|Heute ist nichts fest geplant|Heute (ist|sind) noch/.test(l0[0].text), 'Tageszeile nennt den nächsten Termin mit Uhrzeit oder sagt ehrlich, dass nichts geplant ist');
const ws = D.weekStart(today), last = D.addDays(ws, -7);
const withWeights = { ...empty, weights: Array.from({ length: 21 }, (_, i) => ({ id: `w${i}`, date: D.addDays(today, -20 + i), time: '07:00', kg: 86 - i * 0.08, note: '', source: 'manuell' })) };
const l1 = briefingLines(withWeights, cfg, today, 420);
ok(l1.some(x => x.kind === 'zuletzt' && /Gewichtstrend: −/.test(x.text)), `Bei Ziel „Abnehmen“ und sinkendem Trend positive Aussage (${(l1[1] || {}).text})`);
const cfgFit = D.normalizeConfig({ goals: ['fitter'], onboardingDone: true });
ok(!briefingLines(withWeights, cfgFit, today, 420).some(x => /Gewicht/.test(x.text)), 'Ohne Ziel „Abnehmen“ keine Gewichtsaussage');
const st = D.seed(today, cfg);
const l2 = briefingLines(st, cfg, today, 1439);
ok(l2.length <= 2 && l2.every(x => ['heute', 'zuletzt'].includes(x.kind)), `Höchstens zwei Zeilen plus Handlung (${l2.map(x => x.text).join(' | ')})`);
const allDone = { ...empty, items: empty.items.map(i => (i.date === today ? { ...i, status: 'erledigt' } : i)), habitLog: Object.fromEntries(empty.habits.map(h => [`${h.id}|${today}`, 'done'])) };
ok(/alles erledigt/.test(briefingLines(allDone, cfg, today, 600)[0].text), 'Alles erledigt wird so benannt');
console.log(`\n${n - f} von ${n} Tests Morning Briefing bestanden`);
process.exit(f ? 1 : 0);
